from __future__ import annotations

from .models import ReportData, ReportFinding


def render_markdown_report(report_data: ReportData) -> str:
    """Render a professional, submission-ready Markdown bug bounty report."""
    ex = report_data.executive_summary
    sc = report_data.scope_methodology

    lines: list[str] = []

    # Report Title
    lines.append(f"# Security Assessment & Vulnerability Report — {ex.target}")
    lines.append("")
    lines.append(f"> **Generated by Hunt_Chain Framework** on `{report_data.generated_at}`")
    lines.append(f"> **Scope Authorization Reference**: `{ex.scope_reference}` (State: `{sc.authorization_state}`)")
    lines.append("")
    lines.append("---")
    lines.append("")

    # =========================================================================
    # 1. Executive Summary
    # =========================================================================
    lines.append("## 1. Executive Summary")
    lines.append("")
    lines.append(f"**Target Application**: `{ex.target}`  ")
    lines.append(f"**Authorization Reference**: `{ex.scope_reference}`  ")
    lines.append(f"**Assessment Testing Window**: `{ex.test_run_start}` to `{ex.test_run_end}`  ")
    lines.append("")

    # Status Breakdown Table
    lines.append("### Finding Status Overview")
    lines.append("")
    lines.append("| Status Category | Finding Count | Description |")
    lines.append("| :--- | :---: | :--- |")
    lines.append(f"| **Confirmed** | **{ex.confirmed_count}** | Validated vulnerabilities ready for immediate triage & reporting |")
    lines.append(f"| **Not Confirmed (Candidates)** | **{ex.not_confirmed_count}** | Anomalies requiring manual verification before submission |")
    lines.append(f"| **Manual-Only (Untested)** | **{ex.manual_only_count}** | High-level business logic workflows reserved for manual audit |")
    lines.append(f"| **Total Pipeline Findings** | **{ex.total_findings}** | Combined findings across all 22 vulnerability families |")
    lines.append("")

    # Confirmed Findings Severity Table & ASCII Bar
    lines.append("### Confirmed Severity Distribution")
    lines.append("")
    lines.append("| Severity Level | Count | Distribution Indicator |")
    lines.append("| :--- | :---: | :--- |")
    for sev in ("CRITICAL", "HIGH", "MEDIUM", "LOW"):
        cnt = ex.severity_counts.get(sev, 0)
        bar = "█" * cnt if cnt > 0 else "—"
        lines.append(f"| **{sev}** | {cnt} | `{bar}` |")
    lines.append("")
    lines.append(f"**Severity Distribution Bar**: `{ex.severity_bar}`")
    lines.append("")

    # Lead Summary Paragraph
    lines.append("### Executive Risk Summary")
    lines.append("")
    lines.append(ex.lead_summary_paragraph)
    lines.append("")
    lines.append("---")
    lines.append("")

    # =========================================================================
    # 2. Confirmed Findings (Sorted by Severity)
    # =========================================================================
    lines.append("## 2. Confirmed Findings")
    lines.append("")
    if not report_data.confirmed_findings:
        lines.append("*No confirmed vulnerabilities were identified during this assessment.*")
        lines.append("")
    else:
        for index, finding in enumerate(report_data.confirmed_findings, start=1):
            sev_badge = f"[{finding.severity.upper()}]"
            lines.append(f"### 2.{index} {sev_badge} {finding.title}")
            lines.append("")
            lines.append(f"- **Vulnerability Type / Weakness**: {finding.vulnerability_type} ({finding.cwe_id}: {finding.cwe_name})")
            
            # Severity & CVSS
            cvss_str = f"CVSS 3.1: `{finding.cvss.base_score}` ({finding.cvss.vector_string})" if finding.cvss else finding.cvss_note or "CVSS not calculated for this finding type"
            lines.append(f"- **Severity**: **{finding.severity.upper()}** — {cvss_str}")
            lines.append(f"- **Asset / Endpoint**: `{finding.method} {finding.endpoint or finding.target}`")
            if finding.parameter:
                lines.append(f"- **Vulnerable Parameter**: `{finding.parameter}`")
            if finding.contributing_tester_ids:
                tester_strs = [str(t.get("test_id", t) if isinstance(t, dict) else t) for t in finding.contributing_tester_ids]
                lines.append(f"- **Contributing Tester IDs**: `{', '.join(tester_strs)}`")
            lines.append("")

            # Description
            lines.append("#### Description")
            lines.append(finding.description)
            lines.append("")

            # Steps to Reproduce
            lines.append("#### Steps to Reproduce")
            if finding.steps_to_reproduce:
                for step_idx, step in enumerate(finding.steps_to_reproduce, start=1):
                    lines.append(f"{step_idx}. {step}")
            else:
                lines.append("1. Send a request to the identified endpoint with the targeted payload.")
                lines.append("2. Observe the anomalous response behavior.")
            lines.append("")

            # Evidence (Redacted)
            lines.append("#### Evidence")
            lines.append("```text")
            lines.append(finding.evidence or "[Evidence validated by Hunt_Chain Detection & Validation Layer]")
            lines.append("```")
            lines.append("")

            # Impact
            lines.append("#### Impact")
            lines.append(finding.impact)
            lines.append("")

            # Suggested Remediation
            lines.append("#### Suggested Remediation")
            for rem in finding.suggested_remediation:
                lines.append(f"- {rem}")
            lines.append("")

            # References
            lines.append("#### References")
            for ref in finding.references:
                lines.append(f"- {ref}")
            lines.append("")

            # Chaining / Related Cross-References
            if finding.related_finding_ids:
                lines.append("#### Related Findings (Vulnerability Chaining)")
                for note in finding.related_notes:
                    lines.append(f"> ⚠️ **Chain Warning**: {note}")
                lines.append("")

            lines.append("---")
            lines.append("")

    # =========================================================================
    # 3. Candidates for Manual Review (Not Confirmed)
    # =========================================================================
    lines.append("## 3. Candidates for Manual Review (Not Confirmed)")
    lines.append("")
    lines.append("> [!NOTE]")
    lines.append("> Findings in this section produced anomalous signals during initial detection, but could not be")
    lines.append("> definitively verified by the automated Validation Layer. They require manual researcher review")
    lines.append("> before submitting to a bug bounty program.")
    lines.append("")

    if not report_data.candidates_for_review:
        lines.append("*No unconfirmed candidate findings pending manual review.*")
        lines.append("")
    else:
        for index, candidate in enumerate(report_data.candidates_for_review, start=1):
            lines.append(f"### 3.{index} [UNCONFIRMED] {candidate.title}")
            lines.append("")
            lines.append(f"- **Status**: `UNCONFIRMED — requires manual verification before reporting.`")
            lines.append(f"- **Vulnerability Type / Weakness**: {candidate.vulnerability_type} ({candidate.cwe_id}: {candidate.cwe_name})")
            lines.append(f"- **Asset / Endpoint**: `{candidate.method} {candidate.endpoint or candidate.target}`")
            if candidate.parameter:
                lines.append(f"- **Parameter Under Test**: `{candidate.parameter}`")
            lines.append("")

            lines.append("#### Description")
            lines.append(candidate.description)
            lines.append("")

            lines.append("#### Recommended Manual Verification Steps")
            for step_idx, step in enumerate(candidate.steps_to_reproduce, start=1):
                lines.append(f"{step_idx}. {step}")
            lines.append("")

            lines.append("#### Preliminary Evidence")
            lines.append("```text")
            lines.append(candidate.evidence or "[Anomalous baseline response recorded by initial tester]")
            lines.append("```")
            lines.append("")

            lines.append("#### References")
            for ref in candidate.references:
                lines.append(f"- {ref}")
            lines.append("")
            lines.append("---")
            lines.append("")

    # =========================================================================
    # 4. Manual-Only Checklist (Not Automatically Tested)
    # =========================================================================
    lines.append("## 4. Manual-Only Checklist (Not Automatically Tested)")
    lines.append("")
    lines.append("> [!IMPORTANT]")
    lines.append("> The following security controls represent multi-step business logic and account state workflows")
    lines.append("> that were reserved for manual researcher audit per the project's non-destructive testing policy.")
    lines.append("")

    if not report_data.manual_checklist:
        lines.append("*No manual testing items registered for this scope.*")
        lines.append("")
    else:
        # Group checklist by family
        checklist_by_family: dict[str, list] = {}
        for item in report_data.manual_checklist:
            checklist_by_family.setdefault(item.family, []).append(item)

        for family_name, items in checklist_by_family.items():
            lines.append(f"### {family_name}")
            lines.append("")
            for itm in items:
                lines.append(f"**Target Route**: `{itm.endpoint}` (`{itm.test_id}`)")
                for act in itm.action_items:
                    lines.append(f"- [ ] {act}")
                lines.append("")
            lines.append("")

    lines.append("---")
    lines.append("")

    # =========================================================================
    # 5. Scope & Methodology Appendix
    # =========================================================================
    lines.append("## 5. Scope & Methodology Appendix")
    lines.append("")
    lines.append(f"- **Scope Authorization Decision**: `{sc.authorization_state}` (Rule ID: `{sc.scope_rule_id}`)")
    lines.append(f"- **Authorized Target Asset**: `{sc.authorized_target}`")
    lines.append(f"- **Authorization Timestamp**: `{sc.authorization_timestamp}`")
    lines.append(f"- **Attack Surface Discovered (Project 2)**: `{sc.discovered_assets_count}` assets/endpoints")
    tech_strs = [
        str(t.get("name", t) if isinstance(t, dict) else t)
        for t in sc.technologies_fingerprinted
    ] if sc.technologies_fingerprinted else ["None specified"]
    lines.append(f"- **Technologies Fingerprinted**: {', '.join(tech_strs)}")
    lines.append(f"- **Vulnerability Families Tested (Project 3)**: {len(sc.families_run)} families")
    lines.append(f"- **Total Testers Fired**: `{sc.testers_fired_count}`")
    lines.append(f"- **Total Requests Executed**: `{sc.total_requests_made}` (Budget-compliant)")
    lines.append("")
    lines.append("### Assurance Statement")
    lines.append(f"> {sc.assurance_statement}")
    lines.append("")

    return "\n".join(lines)
